/** Teinte atténuée (ex. bordures de boutons colorés) à partir d'un hex #RRGGBB. */
function alpha(hex: string, opacite: number): string {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return hex;
  const n = parseInt(m[1], 16);
  return `rgba(${(n >> 16) & 0xff}, ${(n >> 8) & 0xff}, ${n & 0xff}, ${opacite})`;
}

